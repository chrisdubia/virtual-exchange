// Generates a SQL seed file for the organizations table from the
// hardcodedOrganizations data module. Run with: node scripts/generate-seed-sql.js
// Then paste migrations/seed-organizations.sql into Supabase SQL editor.

import { hardcodedOrganizations } from '../src/data/organizations.js';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const sqlString = (v) => v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`;
const sqlArray = (arr) => {
  if (!Array.isArray(arr) || arr.length === 0) return "ARRAY[]::text[]";
  return `ARRAY[${arr.map(s => sqlString(s)).join(', ')}]`;
};
const sqlBool = (v) => v ? 'TRUE' : 'FALSE';
const sqlJson = (v) => v == null ? 'NULL' : `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;

const rows = hardcodedOrganizations.map(o => `(
  ${sqlString(o.name)},
  ${sqlString(o.type)},
  ${sqlString(o.category)},
  ${sqlString(o.country)},
  ${sqlString(o.region)},
  ${sqlString(o.description)},
  ${sqlArray(o.languages)},
  ${sqlArray(o.interests)},
  ${sqlString(o.capacity)},
  ${sqlString(o.email)},
  ${sqlString(o.phone)},
  ${sqlBool(o.verified)},
  ${sqlString(o.website)},
  ${sqlArray(o.partnershipGoals)},
  ${sqlJson(o.programs)},
  'approved',
  NOW()
)`).join(',\n');

const sql = `-- Auto-generated by scripts/generate-seed-sql.js
-- Seeds the organizations table with all hardcoded orgs from src/data/organizations.js
-- Safe to re-run: uses ON CONFLICT (name) DO NOTHING.

INSERT INTO organizations (
  name, type, category, country, region, description,
  languages, interests, capacity, email, phone, verified, website,
  partnership_goals, programs,
  approval_status, approved_at
) VALUES
${rows}
ON CONFLICT (name) DO NOTHING;
`;

const outPath = 'migrations/seed-organizations.sql';
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, sql);
console.log(`Wrote ${hardcodedOrganizations.length} orgs → ${outPath}`);
console.log(`File size: ${(sql.length / 1024).toFixed(1)} KB`);
